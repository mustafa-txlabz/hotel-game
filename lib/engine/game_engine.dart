import 'dart:math' as math;

import '../data/balance.dart';
import 'models.dart';

/// Core game logic engine.
///
/// NOTE: Pure Dart class with NO Flutter imports so it can be completely unit tested.
class GameEngine {
  GameState _state;

  GameEngine([GameState? initialState])
    : _state = initialState ?? const GameState();

  GameState get state => _state;

  /// Helper to clamp rupees safely and prevent NaN/Infinity.
  static double sanitizeRupees(double value) {
    if (value.isNaN || value.isInfinite || value < 0.0) return 0.0;
    return value;
  }

  /// Calculates the cost to buy [count] units of a business starting from [owned].
  /// Formula: baseCost * g^owned * (g^n - 1) / (g - 1)
  static double calculateCost({
    required double baseCost,
    required int owned,
    required int count,
    double growthRate = GameBalance.costGrowthRate,
  }) {
    if (count <= 0) return 0.0;
    if (count == 1) {
      return baseCost * math.pow(growthRate, owned);
    }
    final gPowOwned = math.pow(growthRate, owned);
    final gPowNMinus1 = math.pow(growthRate, count) - 1.0;
    final cost = baseCost * gPowOwned * (gPowNMinus1 / (growthRate - 1.0));
    return sanitizeRupees(cost);
  }

  /// Calculates max affordable units given available [cash].
  /// Formula: floor( ln( cash * (g - 1) / (baseCost * g^owned) + 1 ) / ln(g) )
  static int calculateMaxAffordable({
    required double cash,
    required double baseCost,
    required int owned,
    double growthRate = GameBalance.costGrowthRate,
  }) {
    if (cash <= 0.0 || baseCost <= 0.0) return 0;
    final singleCost = baseCost * math.pow(growthRate, owned);
    if (cash < singleCost) return 0;

    final numerator = cash * (growthRate - 1.0) / singleCost + 1.0;
    if (numerator <= 0) return 0;

    final maxAffordable = (math.log(numerator) / math.log(growthRate)).floor();
    return math.max(0, maxAffordable);
  }

  /// Checks if a business is unlocked.
  /// Business 1 (index 1) is always unlocked.
  /// Business N is unlocked if Business N-1 has at least 1 owned unit.
  bool isBusinessUnlocked(String businessId) {
    final config = GameBalance.allBusinesses.firstWhere(
      (b) => b.id == businessId,
      orElse: () => GameBalance.allBusinesses.first,
    );

    if (config.index == 1) return true;

    // Previous business must have at least 1 unit owned
    final prevConfig = GameBalance.allBusinesses[config.index - 2];
    final prevOwned = _state.getBusiness(prevConfig.id).owned;
    return prevOwned >= 1;
  }

  /// Calculates the income per second generated by a single business.
  /// Formula: baseIncome * owned * milestoneMultiplier * upgradeMultiplier
  double businessIncomePerSecond(
    String businessId, {
    double upgradeMultiplier = 1.0,
  }) {
    final config = GameBalance.allBusinesses.firstWhere(
      (b) => b.id == businessId,
      orElse: () => GameBalance.allBusinesses.first,
    );
    final owned = _state.getBusiness(businessId).owned;
    if (owned <= 0) return 0.0;

    final milestoneMult = GameBalance.getMilestoneMultiplier(owned);
    final income =
        config.baseIncome * owned * milestoneMult * upgradeMultiplier;
    return sanitizeRupees(income);
  }

  /// Calculates total game income per second across all businesses,
  /// including prestige (Shohrat) and boost multipliers.
  /// Formula: sum(all businesses) * (1 + 0.03 * shohrat) * boostMultiplier
  double get totalIncomePerSecond {
    double sum = 0.0;
    for (final config in GameBalance.allBusinesses) {
      sum += businessIncomePerSecond(config.id);
    }
    final prestigeMultiplier =
        1.0 + (GameBalance.shohratBonusPercent * _state.shohrat);
    final total = sum * prestigeMultiplier * _state.boostMultiplier;
    return sanitizeRupees(total);
  }

  /// Updates state by a time delta [dt] in seconds.
  void tick(double dt) {
    if (dt <= 0.0) return;

    final income = totalIncomePerSecond * dt;
    if (income <= 0.0) return;

    final newRupees = sanitizeRupees(_state.rupees + income);
    final newLifetime = sanitizeRupees(_state.lifetimeRupees + income);
    final newRun = sanitizeRupees(_state.runRupees + income);

    _state = _state.copyWith(
      rupees: newRupees,
      lifetimeRupees: newLifetime,
      runRupees: newRun,
    );
  }

  /// Taps the chai cup to earn rupees.
  /// Formula: (1 + 0.02 * totalIncomePerSecond) * boostMultiplier
  double tapCup() {
    final tapGain =
        (GameBalance.tapBaseRupees +
            (GameBalance.tapIncomeMultiplier * totalIncomePerSecond)) *
        _state.boostMultiplier;

    final gain = sanitizeRupees(tapGain);
    _state = _state.copyWith(
      rupees: sanitizeRupees(_state.rupees + gain),
      lifetimeRupees: sanitizeRupees(_state.lifetimeRupees + gain),
      runRupees: sanitizeRupees(_state.runRupees + gain),
    );
    return gain;
  }

  /// Returns the cost for the next purchase of [count] units for [businessId].
  double getCost(String businessId, [int count = 1]) {
    final config = GameBalance.allBusinesses.firstWhere(
      (b) => b.id == businessId,
      orElse: () => GameBalance.allBusinesses.first,
    );
    final currentOwned = _state.getBusiness(businessId).owned;
    return calculateCost(
      baseCost: config.baseCost,
      owned: currentOwned,
      count: count,
    );
  }

  /// Checks if player can afford [count] units of [businessId].
  bool canAfford(String businessId, [int count = 1]) {
    if (!isBusinessUnlocked(businessId)) return false;
    final cost = getCost(businessId, count);
    return _state.rupees >= cost;
  }

  /// Buys [count] units of [businessId].
  /// Returns a record: (bool success, bool milestoneHit)
  ({bool success, bool milestoneHit}) buyBusiness(
    String businessId, [
    int count = 1,
  ]) {
    if (!canAfford(businessId, count)) {
      return (success: false, milestoneHit: false);
    }

    final cost = getCost(businessId, count);
    final currentBiz = _state.getBusiness(businessId);
    final previousOwned = currentBiz.owned;
    final newOwned = previousOwned + count;

    // Check if a new milestone was reached
    final prevMilestones = GameBalance.getMilestoneMultiplier(previousOwned);
    final newMilestones = GameBalance.getMilestoneMultiplier(newOwned);
    final milestoneHit = newMilestones > prevMilestones;

    final updatedBiz = currentBiz.copyWith(
      owned: newOwned,
      lastMilestoneClaimed: milestoneHit
          ? newOwned
          : currentBiz.lastMilestoneClaimed,
    );

    final updatedBusinesses = Map<String, BusinessState>.from(
      _state.businesses,
    );
    updatedBusinesses[businessId] = updatedBiz;

    _state = _state.copyWith(
      rupees: sanitizeRupees(_state.rupees - cost),
      businesses: updatedBusinesses,
    );

    return (success: true, milestoneHit: milestoneHit);
  }
}
